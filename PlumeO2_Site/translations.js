/* ── SYSTÈME DE TRADUCTION ──────────────────────────────── */
let currentLang = localStorage.getItem('plumedo2_lang') || 'fr';

function setLanguage(lang) {
  currentLang = lang;
  localStorage.setItem('plumedo2_lang', lang);

  const t = TRANSLATIONS[lang];
  if (!t) return;

  // Appliquer toutes les traductions
  document.querySelectorAll('[data-i18n]').forEach(el => {
    const key = el.getAttribute('data-i18n');
    if (t[key]) el.textContent = t[key];
  });

  // Attributs HTML (placeholder, aria-label, etc.)
  document.querySelectorAll('[data-i18n-attr]').forEach(el => {
    const parts = el.getAttribute('data-i18n-attr').split(':');
    const attr = parts[0];
    const key = parts[1];
    if (t[key]) el.setAttribute(attr, t[key]);
  });

  // Direction RTL pour l'arabe
  document.documentElement.setAttribute('dir', lang === 'ar' ? 'rtl' : 'ltr');
  document.documentElement.setAttribute('lang', lang);

  // Mettre à jour les boutons de langue actifs
  document.querySelectorAll('.lang-btn').forEach(btn => {
    btn.classList.toggle('active', btn.getAttribute('data-lang') === lang);
  });
}

// Initialiser au chargement
document.addEventListener('DOMContentLoaded', () => {
  setLanguage(currentLang);
});
